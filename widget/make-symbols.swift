import AppKit
// Stock mic.fill outline at the template's Regular-M size (100 pt), baseline at y = 0, y down.
let img = NSImage(systemSymbolName: "mic.fill", accessibilityDescription: nil)!.withSymbolConfiguration(.init(pointSize: 100, weight: .regular))!
let rep = img.representations[0]
let g = object_getIvar(rep, class_getInstanceVariable(type(of: rep), "_vectorGlyph")!) as! NSObject
let raw = g.perform(NSSelectorFromString("CGPath"))!.takeUnretainedValue() as! CGPath
let k = 70.0 / raw.boundingBoxOfPath.width
var t = CGAffineTransform(a: k, b: 0, c: 0, d: k, tx: 0, ty: -35.25 - raw.boundingBoxOfPath.height * k / 2)
let mic = raw.copy(using: &t)!
let micBox = mic.boundingBoxOfPath
func lock(open: Bool) -> CGPath {
  let W = 54.0, H = 43.0, bx = 48.0, by = micBox.maxY - H, cx = bx + W / 2, s = 14.0, lift = open ? 8.0 : 0.0
  let body = CGMutablePath(); body.addRoundedRect(in: CGRect(x: bx, y: by, width: W, height: H), cornerWidth: 7, cornerHeight: 7)
  let sh = CGMutablePath()
  sh.move(to: CGPoint(x: cx - s, y: by + 1)); sh.addLine(to: CGPoint(x: cx - s, y: by - 12 - lift))
  sh.addArc(center: CGPoint(x: cx, y: by - 12 - lift), radius: s, startAngle: .pi, endAngle: 0, clockwise: false)
  sh.addLine(to: CGPoint(x: cx + s, y: open ? by - 10 : by + 1))
  let shackle = sh.copy(strokingWithWidth: 8, lineCap: .butt, lineJoin: .round, miterLimit: 4)
  let hole = CGPath(ellipseIn: CGRect(x: cx - 5, y: by + H / 2 - 6, width: 10, height: 10), transform: nil)
  return body.subtracting(hole).union(shackle)
}
func svg(_ p: CGPath, right: Double) -> String {
  var d = ""; func f(_ q: CGPoint) -> String { String(format: "%.2f,%.2f", q.x, q.y) }
  p.applyWithBlock { e in let q = e.pointee.points
    switch e.pointee.type { case .moveToPoint: d += "M\(f(q[0]))"; case .addLineToPoint: d += "L\(f(q[0]))"
    case .addQuadCurveToPoint: d += "Q\(f(q[0])) \(f(q[1]))"; case .addCurveToPoint: d += "C\(f(q[0])) \(f(q[1])) \(f(q[2]))"
    case .closeSubpath: d += "Z"; @unknown default: break } }
  let L = 1400 + micBox.minX - 4, R = 1400 + right + 4
  return """
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">
<!-- Generated by widget/make-symbols.swift: the stock mic.fill outline plus a padlock. -->
<svg version="1.1" xmlns="http://www.w3.org/2000/svg" width="3300" height="2200">
 <g id="Notes">
  <text id="template-version" x="2970" y="2180">Template v.3.0</text>
 </g>
 <g id="Guides">
  <line id="Baseline-S" x1="263" x2="3036" y1="696" y2="696"/>
  <line id="Capline-S" x1="263" x2="3036" y1="625.541" y2="625.541"/>
  <line id="Baseline-M" x1="263" x2="3036" y1="1126" y2="1126"/>
  <line id="Capline-M" x1="263" x2="3036" y1="1055.54" y2="1055.54"/>
  <line id="Baseline-L" x1="263" x2="3036" y1="1556" y2="1556"/>
  <line id="Capline-L" x1="263" x2="3036" y1="1485.54" y2="1485.54"/>
  <line id="left-margin-Regular-M" x1="\(L)" x2="\(L)" y1="1030" y2="1150"/>
  <line id="right-margin-Regular-M" x1="\(R)" x2="\(R)" y1="1030" y2="1150"/>
 </g>
 <g id="Symbols">
  <g id="Regular-M" transform="matrix(1 0 0 1 1400 1126)">
   <path d="\(d)"/>
  </g>
 </g>
</svg>

"""
}
let dir = CommandLine.arguments[1]
for (name, open) in [("miclock", false), ("miclock.open", true)] {
  let l = lock(open: open)
  let gap = l.copy(strokingWithWidth: 7, lineCap: .round, lineJoin: .round, miterLimit: 4).union(l)
  // Drop slivers of the stand's arc left over between the gap and the shackle.
  let cut = CGMutablePath()
  for part in mic.subtracting(gap).componentsSeparated() where part.boundingBoxOfPath.width * part.boundingBoxOfPath.height > 60 { cut.addPath(part) }
  let shape = cut.union(l)
  try! svg(shape, right: shape.boundingBoxOfPath.maxX).write(toFile: "\(dir)/\(name).symbolset/\(name).svg", atomically: true, encoding: .utf8)
  print(name, shape.boundingBoxOfPath)
}
